import express from "express";
import dotenv from "dotenv";
import { GoogleGenAI } from "@google/genai";
import path from "path";
import { fileURLToPath } from "url";

// Current directory
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Load environment variables
dotenv.config({
    path: path.join(__dirname, ".env")
});

// Check API key
if (!process.env.GEMINI_API_KEY) {
    console.error("Error: GEMINI_API_KEY is missing in .env file");
    process.exit(1);
}

// Initialize Express
const app = express();

app.use(express.json());
app.use(express.static(path.join(__dirname, "public")));

// Initialize Gemini
const ai = new GoogleGenAI({
    apiKey: process.env.GEMINI_API_KEY
});

// Chat API
app.post("/chat", async (req, res) => {
    try {
        const { messages } = req.body;

        if (!Array.isArray(messages) || messages.length === 0) {
            return res.status(400).json({
                error: "Please enter a message."
            });
        }

        // Convert frontend messages into Gemini format
        const chatHistory = messages.map((message) => ({
            role: message.role === "assistant" ? "model" : "user",
            parts: [
                {
                    text: String(message.content || "")
                }
            ]
        }));

        // Generate AI response
        let response;
        let attempts = 3;

        for (let i = 1; i <= attempts; i++) {
            try {
                console.log(`Gemini API attempt: ${i}`);

                   response = await ai.models.generateContent({
                   model: "gemini-3.5-flash-lite",
                    contents: chatHistory,
                    config: {
                    systemInstruction: `
                         You are AI Smart Assistant.
                         Answer questions clearly and accurately.
                         Support both Hindi and English.
                         Explain programming concepts in simple language.
                         Give code examples when required.
                         Be friendly and helpful.
                `
            }
        });

        break;

    } catch (error) {
        const errorMessage = String(error.message || "").toLowerCase();

        const isRetryable =
           error.status === 503 ||
           error.status === 429 ||
           error.code === 503 ||
           errorMessage.includes("503") ||
           errorMessage.includes("fetch failed") ||
           errorMessage.includes("unavailable") ||
           errorMessage.includes("econnreset") ||
           errorMessage.includes("etimedout") ||
           errorMessage.includes("enotfound");

       if (!isRetryable || i === attempts) {
          throw error;
}

       console.log("Temporary error. Retrying...");

        await new Promise(resolve =>
            setTimeout(resolve, i * 3000)
        );
    }
}

        const reply = response.text;

        if (!reply) {
            throw new Error("No response generated by Gemini.");
        }

        res.json({
            reply: reply
        });

    } catch (error) {
        console.error("Gemini API Error:", error);

        res.status(500).json({
            error: error.message || "Something went wrong."
        });
    }
});

// Server port
const PORT = 3000;

// Start server
app.listen(PORT, () => {
    console.log(`Server running at http://localhost:${PORT}`);
});